import random


NAME = 'z-最初始压枪宏'         # 宏库中显示的脚本名称
HOTKEY = 'backslash'          # 物理触发键：反斜杠键 \
MODE = 'down'                 # 按住触发键运行，松开立即停止
COUNT = 0                     # 每次按住最多执行一轮，即最多约 2.1 秒
SPEED = 1.0                   # 等待倍率：会缩放"点射重置"的等待，保持 1.0 最稳
ENABLED = False                # 已启用


# ==================== 最常修改的参数 ====================
# 每一行的格式：(“阶段名称”, 持续毫秒, 基础间隔毫秒)
#
# 基础间隔越小，移动越频繁，整体压枪越强。
# 当前总时长：500 + 800 + 800 = 2100ms，也就是 2.1 秒。
#
# 默认手感：前段轻、中段稳定、后段稍强，避免一开枪就突然下拽。
压枪曲线 = (
    ("前段轻压", 500, 24),
    ("中段稳定", 800, 18),
    ("后段加强", 800, 15),
)

# 左右随机范围：按阶段分别设置，顺序与"压枪曲线"三个阶段一一对应。
# 实测弹道是"前段居中 → 中段右移 → 后段向右上飘"，所以补偿策略：
#   前段基本居中（只有小幅抖动）→ 中段开始轻微左拉 → 后段左拉加强。
左右随机范围表 = (
    (-1, 0, 1),           # 前段轻压：居中，只留小幅随机抖动
    (-3, -2, -1, 1),      # 中段稳定：开始向左拉，抵消向右偏移
    (-4, -3, -2, -1, 1),  # 后段加强：左拉加强，抵消向右上飘
)

# 向下随机范围：按阶段分别设置。弹道后段往上飘，所以后段下压要加大。
# 这是 Windows SendInput 相对移动单位，实际观感会受系统和游戏灵敏度影响。
# 想更轻就整体改小；想更强就整体加大，但不建议一次跳太大。
向下随机范围表 = (
    (3, 3, 4),   # 前段轻压：下压适中，保持居中
    (3, 4, 4),   # 中段稳定：下压略增
    (4, 5, 5),   # 后段加强：下压加强，抵消向上飘
)

# 下压随机：每次下压时，在"向下随机范围表"选出的数值上再加 ±2 随机，
# 模拟人手下压幅度的轻微起伏，避免节奏完全一致。
下压随机 = 2

# 时间随机范围：每步在基础间隔附近变化 -1ms、0ms 或 +1ms。
# 差距刻意保持很小，避免忽快忽慢；想关闭就改成：(0,)
间隔随机范围 = (-2, 0, 2)

# ==================== 融合新增的参数 ====================
# ① 点射重置（来自"5 发点射控枪"思路）：
#    每打满"点射发数"步，就松开左键再按住，让游戏重置后坐力曲线，
#    避免子弹进入 10 发、15 发那种最抖的阶段。这里按移动步数计数，约等于子弹数。
每段点射发数 = 8         # 每打 8 发左右重置一次；冲锋枪可改成 3~5
点射重置毫秒 = 100       # 松开到再按住的基础时间，>=100ms 更像人手点射节奏
重置随机毫秒 = 10        # 每次重置在基础时间上再加 ±10ms 随机，避免节奏死板

# ② 扇形跟随（来自"扇形压枪"思路）：
#    让左右抖动跟随当前向下幅度：压得少时左右也摆得小，压得多时左右摆得宽，
#    形状像以"正下方"为中轴的扇形，更接近真实弹道。
#    基准向下取"向下随机范围表"的整体平均值，改向下范围时这里要一起改。
基准向下 = 4.0          # (3+3+4 + 3+4+4 + 4+5+5) / 9 ≈ 3.9，取整为 4.0


def _用户压枪(player):
    """按住左键，按原随机曲线压枪，并叠加"点射重置"和"扇形跟随"。"""
    player.mouse_down("left")
    try:
        步数 = 0
        for 阶段序号, (阶段名称, 持续毫秒, 基础间隔毫秒) in enumerate(压枪曲线):
            # 每个阶段单独计算剩余时间，确保三个阶段合计仍精确为 2100ms。
            剩余毫秒 = 持续毫秒
            本段左右 = 左右随机范围表[阶段序号]
            本段向下 = 向下随机范围表[阶段序号]

            while 剩余毫秒 > 0:
                步数 += 1
                横向移动 = random.choice(本段左右)
                向下移动 = random.choice(本段向下) + random.randint(-下压随机, 下压随机)
                随机间隔 = 基础间隔毫秒 + random.choice(间隔随机范围)
                本步毫秒 = min(剩余毫秒, max(1, 随机间隔))

                # 扇形跟随：左右幅度按当前向下幅度缩放；
                # X 可左右变化，Y 恒为正数，所以只会向下压。
                横向移动 = round(横向移动 * 向下移动 / 基准向下)
                player.mouse_move(
                    横向移动,
                    向下移动,
                    duration_ms=本步毫秒,
                )
                剩余毫秒 -= 本步毫秒

                # 点射重置：打满发数就松开再按住，重置后坐力曲线；
                # 每次等待 100ms ± 10ms 随机，模拟人手点射节奏。
                if 步数 % 每段点射发数 == 0:
                    player.mouse_up("left")
                    player.sleep(点射重置毫秒 + random.randint(-重置随机毫秒, 重置随机毫秒))
                    player.mouse_down("left")
    finally:
        # 无论正常结束、松开触发键还是发生错误，都必须释放左键。
        player.mouse_up("left")


def run(player):
    """程序规定的唯一入口：触发宏后，从这里调用“用户压枪”。"""
    _用户压枪(player)
