import random


NAME = 'z-完美压枪宏'         # 宏库中显示的脚本名称
HOTKEY = 'backslash'         # 保持反斜杠键不变：按一次开启监听，再按一次停止
MODE = 'switch'               # 切换模式：无需一直按住反斜杠键
COUNT = 0                     # 开启后不断检查物理左键，直到再次按反斜杠停止
SPEED = 1.0                   # 保持 1.0 时，左键等待状态约每 10ms 检查一次
ENABLED = False                # 已启用


# ==================== 循环结构说明 ====================
# 本宏是“反斜杠启停 + 物理左键联动”模式：
#   1. 按一次反斜杠：开启监听，但此时不会开火、不会移动鼠标。
#   2. 你亲手按住鼠标左键：按曲线持续压枪。
#   3. 你松开鼠标左键：立即停止移动，并继续等待下一次左键按下。
#   4. 再按一次反斜杠：完全停止本宏。
#
# player.is_physical_pressed() 只读取真实物理输入；本程序自己发送的
# MAPL 模拟输入不会被算进去，因此不会形成宏触发自己的循环。


# ==================== 最常修改的参数 ====================
# 每一行的格式：(“阶段名称”, 持续毫秒, 基础间隔毫秒)
#
# 基础间隔越小，移动越频繁，整体压枪越强。
# 当前总时长：500 + 800 + 800 = 2100ms，也就是 2.1 秒。
#
# 默认手感：前段轻、中段稳定、后段稍强，避免一开枪就突然下拽。
压枪曲线 = (
    ("前段轻压", 500, 24),
    ("中段稳定", 800, 18),
    ("后段加强", 800, 15),
)

# 左右随机范围：按阶段分别设置，顺序与"压枪曲线"三个阶段一一对应。
# 实测（未压枪）弹道是"前段居中 → 中段向左上外飘 → 后段向右下回落收束"的拱形，
# 所以补偿策略：前段基本居中 → 中段轻微左拉（只做小修正）→ 后段几乎不横移
# （后半段子弹本来就收束回中心，再继续拉会反向脱靶，只留小幅抖动）。
左右随机范围表 = (
    (-1, 0, 1),           # 前段轻压：居中（前20%落点正中，不横移）
    (-2, -1, 0, 1),       # 中段稳定：轻微左拉（20%~50%外飘，只做轻修）
    (-1, 0, 1),           # 后段加强：几乎不横移（50%~100%回落收束，防反向脱靶）
)

# 向下随机范围：按阶段分别设置。弹道后段往上飘，所以后段下压要加大。
# 这是 Windows SendInput 相对移动单位，实际观感会受系统和游戏灵敏度影响。
# 想更轻就整体改小；想更强就整体加大，但不建议一次跳太大。
向下随机范围表 = (
    (3, 3, 4),   # 前段轻压：下压适中，保持居中
    (3, 4, 4),   # 中段稳定：下压略增
    (4, 5, 5),   # 后段加强：下压加强，抵消向上飘
)

# 下压随机：每次下压时，在"向下随机范围表"选出的数值上再加 ±2 随机，
# 模拟人手下压幅度的轻微起伏，避免节奏完全一致。
下压随机 = 2

# 时间随机范围：每步在基础间隔附近变化 -1ms、0ms 或 +1ms。
# 差距刻意保持很小，避免忽快忽慢；想关闭就改成：(0,)
间隔随机范围 = (-2, 0, 2)

# ==================== 初版算法参数：点射重置 + 扇形跟随 ====================
# ① 点射重置（完整保留初版参数和思想）：
#    作用：打了一小段子弹后，模拟"松开左键 → 停一下 → 再按住左键"，
#          让游戏重置后坐力曲线，避免后段弹道越来越飘。
#    ★ 怎么理解"每段点射发数"：
#       它就是一个数字，控制"打几发子弹就重新射击一次"。
#       · 数值 = 8 → 每打 8 发，就松开再按住一次（当前设置）
#       · 数值 = 5 → 每打 5 发，就松开再按住一次（你要改成的间隔）
#    ★ 怎么改成"间隔 5 发"：
#       只需要把下面这一行里的数字 8 改成 5 即可，其它代码不用动。
每段点射发数 = 8         # ★★★ 想改成"间隔 5 发"，把这里的 8 改成 5 ★★★
点射重置毫秒 = 100       # 松开到再按住的基础时间，>=100ms 更像人手点射节奏
重置随机毫秒 = 10        # 每次重置在基础时间上再加 ±10ms 随机，避免节奏死板

# ② 扇形跟随：
#    让左右抖动跟随当前向下幅度：压得少时左右也摆得小，压得多时左右摆得宽，
#    形状像以"正下方"为中轴的扇形，更接近真实弹道。
#    基准向下取"向下随机范围表"的整体平均值，改向下范围时这里要一起改。
基准向下 = 4.0          # (3+3+4 + 3+4+4 + 4+5+5) / 9 ≈ 3.9，取整为 4.0


def _用户压枪(player):
    """物理左键按住时，执行初版的随机曲线、点射重置和扇形跟随。"""
    player.mouse_down("left")
    try:
        步数 = 0
        for 阶段序号, (阶段名称, 持续毫秒, 基础间隔毫秒) in enumerate(压枪曲线):
            # 初版每个阶段单独计算剩余时间；新增的物理判断只负责松手停止。
            剩余毫秒 = 持续毫秒
            本段左右 = 左右随机范围表[阶段序号]
            本段向下 = 向下随机范围表[阶段序号]

            while 剩余毫秒 > 0 and player.is_physical_pressed("mouse_left"):
                步数 += 1
                横向移动 = random.choice(本段左右)
                向下移动 = random.choice(本段向下) + random.randint(-下压随机, 下压随机)
                随机间隔 = 基础间隔毫秒 + random.choice(间隔随机范围)
                本步毫秒 = min(剩余毫秒, max(1, 随机间隔))

                # 初版扇形跟随：左右幅度按当前向下幅度缩放。
                横向移动 = round(横向移动 * 向下移动 / 基准向下)
                player.mouse_move(横向移动, 向下移动, duration_ms=本步毫秒)
                剩余毫秒 -= 本步毫秒

                # 点射重置的判断（初版算法原样保留）：
                #   "步数" 每走一步就 +1，"步数 % 每段点射发数 == 0" 的意思是：
                #   步数刚好能被"每段点射发数"整除时（8、16、24……）触发一次重置，
                #   也就是"每打满 8 发就重新射击一次"。
                #   ★ 想改成"间隔 5 发"：把上面参数区的 每段点射发数 从 8 改成 5 即可，
                #     这里会自动在 5、10、15…… 处触发，下面这几行代码不需要改。
                if 步数 % 每段点射发数 == 0:
                    player.mouse_up("left")
                    player.sleep(
                        点射重置毫秒
                        + random.randint(-重置随机毫秒, 重置随机毫秒)
                    )
                    # 若用户在随机等待期间松开物理左键，就不能再模拟按下。
                    if not player.is_physical_pressed("mouse_left"):
                        return
                    player.mouse_down("left")
    finally:
        # 沿用初版的停止释放；物理松手、反斜杠停止或异常都不会遗留左键。
        player.mouse_up("left")

def _平A(player, 按住毫秒, 等待毫秒=0):
    """按一次平A（鼠标左键）：按住左键"按住毫秒"后松开，可再等待"等待毫秒"。

    用途：宏最开始先补一次普通点击（用来点按钮/交互物）；
    点击结束后再进入压枪流程，互不影响。
    """
    player.mouse_click("left", hold_ms=按住毫秒)
    if 等待毫秒:
        player.sleep(等待毫秒)


def run(player):
    """等待物理左键；按住时先执行一次平A点击，再压枪，松开后返回等待下一次。"""
    while not player.is_physical_pressed("mouse_left"):
        # 可中断等待：再次按反斜杠或关闭程序时能立即停止，不会空转占 CPU。
        player.sleep(10)
    # —— 最开始先执行一次平A点击（用于点东西），然后才进入压枪 ——
    _平A(player, 37, 30)   # 按住左键 37ms 完成一次点击，再等 30ms
    _用户压枪(player)
